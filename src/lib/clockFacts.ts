export function pickClockFact(previous?: string | null): string {
  if (CLOCK_FACTS.length === 1) return CLOCK_FACTS[0];
  const pool = previous ? CLOCK_FACTS.filter((f) => f !== previous) : CLOCK_FACTS;
  return pool[Math.floor(Math.random() * pool.length)];
}
